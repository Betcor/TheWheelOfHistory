package kolo.protocol.message;

/** Фаза року сесії, що працює. */
public enum YearPhase {
    /** Звіт про минулий рік, анімація важливих коліс на клієнтах. */
    START_OF_YEAR,
    /** Гравці віддають накази; кінець — коли всі натиснули «Готово». */
    ORDERS,
    /** Сервер закрив прийом наказів і розв'язує рік. */
    RESOLVING,
    /** Рік розв'язано й збережено; клієнти отримують його підсумок. */
    REPORT
}
