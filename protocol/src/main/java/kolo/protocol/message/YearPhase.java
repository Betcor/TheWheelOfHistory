package kolo.protocol.message;

/** Фаза року сесії, що працює, або пауза сесії посеред року. */
public enum YearPhase {
    /**
     * Перед першим роком нового світу: гравці переглядають генерацію своїх держав (GD §4.12). Кінець — коли всі
     * гравці на зв'язку натиснули «Готово»; таймера ходу немає. Далі — {@link #START_OF_YEAR} того самого року.
     */
    GENERATION,
    /** Звіт про минулий рік, анімація важливих коліс на клієнтах. */
    START_OF_YEAR,
    /** Гравці віддають накази; кінець — коли всі натиснули «Готово». */
    ORDERS,
    /** Сервер закрив прийом наказів і розв'язує рік. */
    RESOLVING,
    /** Рік розв'язано й збережено; клієнти отримують його підсумок. */
    REPORT,
    /**
     * Рік не вдалося розв'язати чи зберегти: сесію призупинено, стан і файл — на початку року. Чекає, поки хост
     * відновить рік ({@link ClientMessage.Resume}).
     */
    PAUSED
}
