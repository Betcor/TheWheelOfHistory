package kolo.protocol;

/** Сталі протоколу клієнт-сервер. */
public final class Protocol {

    /**
     * Версія протоколу. Клієнт і сервер звіряють її при рукостисканні; будь-яка несумісна зміна повідомлень чи їхнього
     * JSON підвищує версію.
     */
    public static final int VERSION = 1;

    /**
     * Найбільший фрейм — одне повідомлення в JSON, байтів. Великі дані (карта) ідуть частинами, тож фрейм лишається
     * малим; більший вхідний фрейм — ознака пошкодженого потоку або чужого клієнта.
     */
    public static final int MAX_FRAME_BYTES = 4 * 1024 * 1024;

    /** Скільки комірок карти в одній частині ({@code MapCells}): ~250 КБ JSON. */
    public static final int MAP_CHUNK_CELLS = 1000;

    /**
     * Типовий TCP-порт сервера (LAN-хост, окремий сервер). Не частина формату повідомлень: зміна не змінює версії.
     */
    public static final int DEFAULT_PORT = 19_700;

    private Protocol() {}
}
